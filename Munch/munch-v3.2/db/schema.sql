-- Munch initial schema (PostgreSQL / Neon)
-- Idempotent: safe to run repeatedly against the production branch.

create table if not exists profiles (
  id            text primary key,
  display_name  text not null,
  handle        text unique,
  created_at    timestamptz not null default now()
);

comment on table profiles is 'App-level diner profile. Auth provider IDs can be added later.';

alter table profiles add column if not exists last_location jsonb;

comment on column profiles.last_location is 'Most recent opt-in location snapshot: {"lat":37.77,"lng":-122.42,"accuracy_m":18,"label":"Hayes Valley","source":"gps","updated_at":"..."}.';

create table if not exists user_locations (
  id           bigint generated by default as identity primary key,
  profile_id   text not null references profiles (id) on delete cascade,
  lat          double precision not null check (lat between -90 and 90),
  lng          double precision not null check (lng between -180 and 180),
  accuracy_m   double precision check (accuracy_m is null or accuracy_m >= 0),
  label        text,
  source       text not null default 'gps' check (source in ('gps', 'map', 'manual', 'ip')),
  recorded_at  timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

comment on table user_locations is 'Append-only history of opt-in diner locations for recent-area lookup.';
comment on column user_locations.accuracy_m is 'Reported GPS accuracy radius in metres.';

create index if not exists user_locations_profile_recent_idx
  on user_locations (profile_id, updated_at desc);
create index if not exists user_locations_profile_recorded_idx
  on user_locations (profile_id, recorded_at desc);
create index if not exists user_locations_updated_at_idx
  on user_locations (updated_at);

create or replace function prune_user_locations(retention_days integer default 30)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  removed integer;
  cutoff timestamptz;
begin
  if retention_days is null or retention_days < 1 then
    raise exception 'retention_days must be a positive integer';
  end if;

  cutoff := now() - make_interval(days => retention_days);

  delete from user_locations
  where updated_at < cutoff;
  get diagnostics removed = row_count;

  -- A stale "last known" snapshot should not outlive the history it summarises.
  update profiles
     set last_location = null
   where last_location is not null
     and jsonb_typeof(last_location -> 'updated_at') = 'string'
     and (last_location ->> 'updated_at') ~ '^\d{4}-\d{2}-\d{2}'
     and (last_location ->> 'updated_at')::timestamptz < cutoff;

  return removed;
end;
$fn$;

comment on function prune_user_locations(integer) is 'Deletes location history older than the retention window (default 30 days) and clears stale last_location snapshots. Returns deleted history rows.';

create table if not exists restaurants (
  id            text primary key,
  slug          text,
  area_id       text not null,
  area_label    text not null,
  city          text not null,
  name          text not null,
  cuisine       text not null,
  categories    text[] not null default '{}',
  rating        numeric(2,1) check (rating is null or rating between 0 and 5),
  review_count  integer check (review_count is null or review_count >= 0),
  price_level   text,
  address       text not null default '',
  neighborhood  text,
  lat           double precision not null check (lat between -90 and 90),
  lng           double precision not null check (lng between -180 and 180),
  phone         text,
  website       text,
  maps_url      text,
  hours         jsonb,
  timezone      text not null default 'America/Los_Angeles',
  source        text not null default 'bundled' check (source in ('bundled', 'osm', 'user')),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

comment on table restaurants is 'Venue catalogue: bundled Google-derived places plus live OpenStreetMap venues.';
comment on column restaurants.hours is 'Weekly opening hours: {"monday":[[600,1320]], ...} in venue-local minutes.';
comment on column restaurants.source is 'Where the row came from; OSM rows use ids like osm:node:123.';

create index if not exists restaurants_area_idx on restaurants (area_id, name);
create index if not exists restaurants_cuisine_idx on restaurants (cuisine);
create index if not exists restaurants_rating_idx on restaurants (rating desc nulls last);
create index if not exists restaurants_lat_lng_idx on restaurants (lat, lng);
create index if not exists restaurants_categories_idx on restaurants using gin (categories);
create index if not exists restaurants_source_idx on restaurants (source);

create table if not exists saved_cravings (
  id             uuid primary key default gen_random_uuid(),
  profile_id     text not null references profiles (id) on delete cascade,
  restaurant_id  text not null references restaurants (id) on delete cascade,
  state          text not null default 'next' check (state in ('next', 'been')),
  note           text,
  saved_at       timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  constraint saved_cravings_unique_place unique (profile_id, restaurant_id)
);

comment on table saved_cravings is 'A diner shortlist. One row per profile and restaurant.';

create index if not exists saved_cravings_profile_idx on saved_cravings (profile_id, saved_at desc);
create index if not exists saved_cravings_try_next_idx on saved_cravings (profile_id, saved_at desc) where state = 'next';
create index if not exists saved_cravings_restaurant_idx on saved_cravings (restaurant_id);

create table if not exists bookings (
  id                uuid primary key default gen_random_uuid(),
  profile_id        text not null references profiles (id) on delete cascade,
  restaurant_id     text not null references restaurants (id) on delete restrict,
  reservation_date  date not null,
  reservation_time  time not null,
  party_size        smallint not null check (party_size between 1 and 20),
  status            text not null default 'pending' check (status in ('pending', 'confirmed', 'cancelled')),
  special_requests  text,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

comment on table bookings is 'Table reservations. Cancelling keeps history; deleting a venue is blocked.';

create index if not exists bookings_profile_date_idx on bookings (profile_id, reservation_date, reservation_time);
create index if not exists bookings_restaurant_date_idx on bookings (restaurant_id, reservation_date);
create index if not exists bookings_active_idx on bookings (reservation_date, reservation_time) where status in ('pending', 'confirmed');

create table if not exists waitlists (
  id              uuid primary key default gen_random_uuid(),
  profile_id      text not null references profiles (id) on delete cascade,
  restaurant_id   text not null references restaurants (id) on delete cascade,
  party_size      smallint not null check (party_size between 1 and 20),
  queue_position  smallint not null check (queue_position >= 1),
  queue_size      smallint not null check (queue_size >= 1),
  status          text not null default 'waiting' check (status in ('waiting', 'seated', 'left', 'expired')),
  joined_at       timestamptz not null default now(),
  notified_at     timestamptz,
  expires_at      timestamptz,
  constraint waitlists_queue_sane check (queue_size >= queue_position)
);

comment on table waitlists is 'Live queue entries; at most one waiting entry per diner and venue.';

create index if not exists waitlists_restaurant_queue_idx on waitlists (restaurant_id, status, queue_position);
create index if not exists waitlists_profile_idx on waitlists (profile_id, status);
create unique index if not exists waitlists_one_active_idx on waitlists (profile_id, restaurant_id) where status = 'waiting';

