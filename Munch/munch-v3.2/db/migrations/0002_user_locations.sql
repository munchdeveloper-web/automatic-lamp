-- 0002 — remember the diner's last opt-in location and keep a recent history.
-- Idempotent; equivalent DDL is part of db/schema.sql.

alter table profiles add column if not exists last_location jsonb;

comment on column profiles.last_location is 'Most recent opt-in location snapshot: {"lat":37.77,"lng":-122.42,"accuracy_m":18,"label":"Hayes Valley","source":"gps","updated_at":"..."}.';

create table if not exists user_locations (
  id           bigint generated by default as identity primary key,
  profile_id   text not null references profiles (id) on delete cascade,
  lat          double precision not null check (lat between -90 and 90),
  lng          double precision not null check (lng between -180 and 180),
  accuracy_m   double precision check (accuracy_m is null or accuracy_m >= 0),
  label        text,
  source       text not null default 'gps' check (source in ('gps', 'map', 'manual', 'ip')),
  recorded_at  timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

comment on table user_locations is 'Append-only history of opt-in diner locations for recent-area lookup.';
comment on column user_locations.accuracy_m is 'Reported GPS accuracy radius in metres.';

create index if not exists user_locations_profile_recent_idx
  on user_locations (profile_id, updated_at desc);
create index if not exists user_locations_profile_recorded_idx
  on user_locations (profile_id, recorded_at desc);
